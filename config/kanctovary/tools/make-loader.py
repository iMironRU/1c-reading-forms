def build_module(records):
    lines = ["// Сгенерировано make-loader.py из kanctovary.data.yaml. Не править руками.",
             "",
             "Процедура Загрузить(ПутьРезультата) Экспорт",
             "",
             "\tСсылки = Новый Соответствие;",
             "\tПерем Об, Стр;",
             ""]
    lines = lines[:5] + lines[6:]   # «Перем» в теле процедуры 1С не разрешает
    for name in CATALOG_ORDER:
        lines += catalog_code(name, records.get(f"Справочник.{name}", []))
        lines.append("")
    docs = []
    for kind in DOC_KINDS:
        for d in records.get(f"Документ.{kind}", []):
            docs.append((d["Дата"], kind, d))
    # по хронологии: проведение пишет движения в порядке жизни фирмы
    for _, kind, d in sorted(docs, key=lambda x: x[0]):
        lines += document_code(kind, d)
        lines.append("")
    lines += ["\tВыгрузить(ПутьРезультата);", "", "КонецПроцедуры", DUMP]
    return "﻿" + "\n".join(lines)


APP_MODULE = """﻿// Временный обработчик сборки базы: в конфигурацию «Канцтовары» не входит.
Процедура ПриНачалеРаботыСистемы()

	Если СтрНачинаетсяС(ПараметрЗапуска, "ЗАГРУЗИТЬ:") Тогда
		ЗагрузкаКанцтоваров.Загрузить(Сред(ПараметрЗапуска, 11));
		ЗавершитьРаботуСистемы(Ложь);
	КонецЕсли;

КонецПроцедуры
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--out", required=True, help="каталог временной копии src")
    args = ap.parse_args()

    records = yaml.safe_load(open(args.data, encoding="utf-8"))["records"]
    module_dir = os.path.join(args.out, "CommonModules", "ЗагрузкаКанцтоваров", "Ext")
    os.makedirs(module_dir, exist_ok=True)
    open(os.path.join(module_dir, "Module.bsl"), "w", encoding="utf-8").write(build_module(records))
    os.makedirs(os.path.join(args.out, "Ext"), exist_ok=True)
    open(os.path.join(args.out, "Ext", "ManagedApplicationModule.bsl"), "w", encoding="utf-8").write(APP_MODULE)
    print("загрузчик сгенерирован:", module_dir)


if __name__ == "__main__":
    main()
